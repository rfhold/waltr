val rustlsPlatformVerifierAndroid = run {
    val metadata = providers.exec {
        workingDir = rootProject.projectDir
        commandLine(
            "cargo",
            "metadata",
            "--format-version",
            "1",
            "--filter-platform",
            "aarch64-linux-android",
            "--manifest-path",
            "../../Cargo.toml",
        )
    }.standardOutput.asText.get()
    val packages = (JsonSlurper().parseText(metadata) as Map<*, *>)["packages"] as List<*>
    val packageMetadata = packages
        .map { it as Map<*, *> }
        .single { it["name"] == "rustls-platform-verifier-android" }
    val manifest = file(packageMetadata["manifest_path"] as String)
    Pair(File(manifest.parentFile, "maven"), packageMetadata["version"] as String)
}

