//! Runtime helpers for the opinionated progressive-workflow server pattern.

use jaq_interpret::{Ctx, FilterT as _, ParseCtx, RcIter, Val};
use serde::Deserialize;
use serde_json::{Value, json};

use crate::{
    McpPromptDefinition, McpPromptResult, McpResourceDefinition, McpResourceResult,
    McpResourceTemplateDefinition, McpToolDefinition, McpToolResult,
    server::{ServerError, ServerResult},
};

/// Name of the single tool exposed by progressive servers.
pub const EXEC_TOOL_NAME: &str = "exec";

/// Parsed arguments for the progressive `exec` tool.
#[derive(Debug, Clone, Deserialize)]
pub struct ExecRequest {
    /// Dot-notated action name.
    pub action: String,
    /// Action-specific input.
    #[serde(default)]
    pub input: Option<Value>,
    /// Optional jq-compatible filter applied to the JSON output.
    #[serde(default)]
    pub filter: Option<String>,
}

/// JSON schema for one configured action input.
#[derive(Debug, Clone)]
pub struct ActionInputSchema {
    /// Action that accepts this input schema.
    pub action: &'static str,
    /// JSON schema for the input, or `None` for no-input actions.
    pub schema: Option<Value>,
}

/// Namespace help metadata generated by `#[mcp::progressive_server]`.
#[derive(Debug, Clone)]
pub struct ProgressiveNamespace {
    /// Namespace name.
    pub name: &'static str,
    /// Why and when clients should use the namespace.
    pub description: String,
}

/// Action help metadata generated by `#[mcp::progressive_server]`.
#[derive(Debug, Clone)]
pub struct ProgressiveActionHelp {
    /// Dot-notated action name.
    pub name: &'static str,
    /// Namespace that owns the action.
    pub namespace: &'static str,
    /// First doc-comment line.
    pub description: String,
    /// Remaining doc-comment body.
    pub guidance: String,
    /// JSON schema for the action input.
    pub input_schema: Option<Value>,
    /// Fixed resource URI exposed for this action.
    pub resource: Option<&'static str>,
    /// Resource template URI exposed for this action.
    pub resource_template: Option<&'static str>,
}

/// Workflow help metadata generated by `#[mcp::progressive_server]`.
#[derive(Debug, Clone)]
pub struct ProgressiveWorkflowHelp {
    /// Workflow name.
    pub name: &'static str,
    /// First doc-comment line.
    pub description: String,
    /// Remaining doc-comment body.
    pub guidance: String,
}

/// Parse the `exec` tool arguments.
pub fn parse_exec_arguments(arguments: Value) -> ServerResult<ExecRequest> {
    let request = serde_json::from_value::<ExecRequest>(arguments)
        .map_err(|error| ServerError::invalid_params(format!("invalid exec arguments: {error}")))?;
    if request.action.trim().is_empty() {
        return Err(ServerError::invalid_params(
            "missing exec action; call `help` first",
        ));
    }
    Ok(request)
}

/// Deserialize action input with a help-oriented error message.
pub fn deserialize_action_input<T>(
    action: &str,
    namespace: &str,
    input: Option<Value>,
) -> ServerResult<T>
where
    T: serde::de::DeserializeOwned,
{
    let input = input.ok_or_else(|| {
        ServerError::invalid_params(format!(
            "missing input for action `{action}`; call `help.{namespace}`"
        ))
    })?;
    serde_json::from_value(input).map_err(|error| {
        ServerError::invalid_params(format!(
            "invalid input for action `{action}`: {error}; call `help.{namespace}`"
        ))
    })
}

/// Reject input supplied to a no-input action.
pub fn ensure_no_action_input(action: &str, input: Option<Value>) -> ServerResult<()> {
    match input {
        None | Some(Value::Null) => Ok(()),
        Some(Value::Object(object)) if object.is_empty() => Ok(()),
        Some(_) => Err(ServerError::invalid_params(format!(
            "action `{action}` does not accept input"
        ))),
    }
}

/// Create the generated progressive `exec` tool definition.
#[must_use]
pub fn exec_tool_definition(input_schema: Value) -> McpToolDefinition {
    McpToolDefinition {
        name: EXEC_TOOL_NAME.to_owned(),
        title: Some("Execute progressive action".to_owned()),
        description: Some(
            "Run one progressive action. Use action `help` first unless the user provided a specific action."
                .to_owned(),
        ),
        icons: Vec::new(),
        input_schema,
        output_schema: None,
        task_support: None,
        annotations: None,
    }
}

/// Build the generated `exec` input schema.
#[must_use]
pub fn exec_input_schema(
    actions: &[&str],
    inputs: Vec<ActionInputSchema>,
    workflows: &[&str],
) -> Value {
    let help_actions = std::iter::once("help".to_owned())
        .chain(
            actions
                .iter()
                .filter_map(|action| action.split_once('.').map(|(namespace, _)| namespace))
                .map(help_action),
        )
        .chain(std::iter::once("help.workflows".to_owned()))
        .collect::<std::collections::BTreeSet<_>>();
    let all_actions = help_actions
        .iter()
        .map(String::as_str)
        .chain(std::iter::once("workflows.load"))
        .chain(actions.iter().copied())
        .collect::<Vec<_>>();
    let mut input_options = Vec::new();
    input_options.push(json!({
        "title": "help actions",
        "description": "No input. Use with `help`, namespace help actions, and `help.workflows`.",
        "type": "null"
    }));
    input_options.extend(inputs.into_iter().map(|input| {
        let mut schema = input.schema.unwrap_or_else(|| json!({ "type": "null" }));
        if let Value::Object(object) = &mut schema {
            object
                .entry("title".to_owned())
                .or_insert_with(|| Value::String(format!("{} input", input.action)));
            object
                .entry("description".to_owned())
                .or_insert_with(|| Value::String(format!("Use with action `{}`.", input.action)));
        }
        schema
    }));
    input_options.push(json!({
        "title": "workflows.load input",
        "description": "Use with action `workflows.load` to load one configured workflow.",
        "type": "object",
        "additionalProperties": false,
        "required": ["workflow"],
        "properties": { "workflow": { "type": "string", "enum": workflows } }
    }));
    json!({
        "type": "object",
        "additionalProperties": false,
        "required": ["action"],
        "properties": {
            "action": {
                "type": "string",
                "description": "Dot-notated progressive action. Start with `help` unless the user already named an action.",
                "enum": all_actions
            },
            "input": {
                "description": "Action-specific input. Help actions take no input; `workflows.load` takes `{ workflow }`.",
                "oneOf": input_options
            },
            "filter": {
                "type": "string",
                "description": "Optional jq-compatible filter applied to the action JSON output. Examples: `.id`, `.[].id`, `[.[] | .id]`."
            }
        }
    })
}

/// Build a JSON schema for a Rust input type using `schemars`.
#[must_use]
pub fn json_schema_for<T>() -> Value
where
    T: schemars::JsonSchema,
{
    serde_json::to_value(schemars::schema_for!(T)).unwrap_or_else(|_| json!({ "type": "object" }))
}

/// Build auto-generated server instructions.
#[must_use]
pub fn instructions(description: Option<&str>) -> String {
    let mut instructions = String::new();
    if let Some(description) = description.filter(|description| !description.trim().is_empty()) {
        instructions.push_str(description.trim());
        instructions.push_str("\n\n");
    }
    instructions.push_str(
        "This server exposes a single tool, `exec`. Use `exec` with action `help` first unless the user has already provided a specific progressive action or workflow. Use namespace help actions such as `help.<namespace>` to decide why and when to call specific actions.",
    );
    instructions
}

/// Build root help describing each namespace.
#[must_use]
pub fn root_help(
    description: Option<&str>,
    namespaces: &[ProgressiveNamespace],
    workflows: &[ProgressiveWorkflowHelp],
) -> Value {
    json!({
        "topic": "help",
        "description": description.unwrap_or_default(),
        "guidance": "Use a namespace help action to learn why and when to use specific actions before calling them.",
        "namespaces": namespaces.iter().map(|namespace| json!({
            "namespace": namespace.name,
            "description": namespace.description,
            "help_action": help_action(namespace.name)
        })).collect::<Vec<_>>(),
        "workflows": {
            "description": "Configured progressive workflows are available as prompts, resources, and through `workflows.load`.",
            "help_action": "help.workflows",
            "load_action": "workflows.load",
            "count": workflows.len()
        }
    })
}

/// Build namespace help listing its actions and when to use each one.
#[must_use]
pub fn namespace_help(
    namespace: &ProgressiveNamespace,
    actions: &[ProgressiveActionHelp],
) -> Value {
    json!({
        "topic": help_action(namespace.name),
        "namespace": namespace.name,
        "description": namespace.description,
        "actions": actions.iter().map(action_help_value).collect::<Vec<_>>()
    })
}

/// Build workflow help listing configured workflows.
