/// Build a generated progressive tool input schema.
#[must_use]
pub fn input_schema(actions: &[&str], inputs: Vec<ActionInputSchema>, runbooks: &[&str]) -> Value {
    let help_actions = std::iter::once("help".to_owned())
        .chain(
            actions
                .iter()
                .filter_map(|action| action.split_once('.').map(|(namespace, _)| namespace))
                .map(help_action),
        )
        .chain((!runbooks.is_empty()).then_some("help.runbooks".to_owned()))
        .collect::<std::collections::BTreeSet<_>>();
    let all_actions = help_actions
        .iter()
        .map(String::as_str)
        .chain((!runbooks.is_empty()).then_some("runbooks.load"))
        .chain(actions.iter().copied())
        .collect::<Vec<_>>();
    let mut input_options = Vec::new();
    input_options.push(json!({
        "title": "help actions",
        "description": "No input. Use with `help`, namespace help actions, and `help.runbooks`.",
        "type": "null"
    }));
    input_options.extend(inputs.into_iter().map(|input| {
        let mut schema = input.schema.unwrap_or_else(|| json!({ "type": "null" }));
        if let Value::Object(object) = &mut schema {
            object
                .entry("title".to_owned())
                .or_insert_with(|| Value::String(format!("{} input", input.action)));
            object
                .entry("description".to_owned())
                .or_insert_with(|| Value::String(format!("Use with action `{}`.", input.action)));
        }
        schema
    }));
    if !runbooks.is_empty() {
        input_options.push(json!({
            "title": "runbooks.load input",
            "description": "Use with action `runbooks.load` to load one configured runbook.",
            "type": "object",
            "additionalProperties": false,
            "required": ["runbook"],
            "properties": { "runbook": { "type": "string", "enum": runbooks } }
        }));
    }
    json!({
        "type": "object",
        "additionalProperties": false,
        "required": ["action"],
        "properties": {
            "action": {
                "type": "string",
                "description": "Progressive action. Start with `help` unless the user already named an action.",
                "enum": all_actions
            },
            "input": {
                "description": "Action-specific input. Help actions take no input; `runbooks.load` takes `{ runbook }`.",
                "oneOf": input_options
            },
            "filter": {
                "type": ["string", "null"],
                "description": "Optional jq-compatible filter applied to the action JSON output. Examples: `.id`, `.[].id`, `[.[] | .id]`."
            }
        }
    })
}

