/// Parse the `workflows.load` input.
pub fn workflow_load_input(input: Option<Value>) -> ServerResult<String> {
    #[derive(Deserialize)]
    struct Input {
        workflow: String,
    }

    let input = input.ok_or_else(|| {
        ServerError::invalid_params(
            "missing input for action `workflows.load`; call `help.workflows`",
        )
    })?;
    let input = serde_json::from_value::<Input>(input).map_err(|error| {
        ServerError::invalid_params(format!(
            "invalid input for action `workflows.load`: {error}; call `help.workflows`"
        ))
    })?;
    Ok(input.workflow)
}

