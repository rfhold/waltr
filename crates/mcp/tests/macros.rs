use std::{net::SocketAddr, sync::Arc, sync::Mutex};

use mcp::{
    McpAccessToken, McpCompletionRequest, McpCompletionResult, McpPromptDefinition,
    McpPromptResult, McpProtectedResourceMetadata, McpResourceDefinition, McpResourceResult,
    McpResourceTemplateDefinition, McpTokenValidation, McpToolCall, McpToolDefinition,
    McpToolResult,
    protocol::MCP_PROTOCOL_VERSION,
    server::{McpAuthorizationContext, ServerContext, ServerError, ServerResult},
};
use reqwest::StatusCode;
use serde_json::{Value, json};
use tokio::{net::TcpListener, task::JoinHandle};

#[derive(Clone, Default)]
struct MacroServer {
    validations: Arc<Mutex<Vec<String>>>,
}

#[mcp::mcp_server(
    name = "mcp-macro-test-server",
    version = "1.2.3",
    description = "Generated by the exported MCP server macro.",
    tools_next_cursor = "next-tool-page",
    prompts_next_cursor = "next-prompt-page",
    resources_next_cursor = "next-resource-page",
    resource_templates_next_cursor = "next-template-page",
    auth(
        scopes = ["macro:read"],
        required_scopes = ["macro:read"],
        realm = "mcp-macro-test",
        resource_name = "MCP macro test server"
    )
)]
impl MacroServer {
    #[instructions]
    fn instructions() -> Option<String> {
        Some("Prefer macro-generated handlers.".to_owned())
    }

    #[tool(name = "echo", definition = echo_tool_definition())]
    async fn echo_tool(call: McpToolCall, _context: ServerContext) -> ServerResult<McpToolResult> {
        let value = call
            .arguments
            .get("value")
            .and_then(Value::as_str)
            .ok_or_else(|| ServerError::invalid_params("missing value"))?;
        Ok(McpToolResult::text(format!("echo:{value}")))
    }

    #[prompt(name = "status", definition = status_prompt_definition())]
    fn status_prompt(
        _arguments: Option<Value>,
        _context: ServerContext,
    ) -> ServerResult<McpPromptResult> {
        Ok(McpPromptResult::text_user("macro-prompt-status"))
    }

    #[resource(uri = "test://status", definition = status_resource_definition())]
    #[resource_template(uri_template = "test://items/{id}", definition = item_template_definition())]
    fn read_resource(uri: String, _context: ServerContext) -> ServerResult<McpResourceResult> {
        Ok(McpResourceResult::text(
            uri.clone(),
            "text/plain",
            format!("resource:{uri}"),
        ))
    }

    #[complete]
    fn complete(
        request: McpCompletionRequest,
        _context: ServerContext,
    ) -> ServerResult<McpCompletionResult> {
        Ok(McpCompletionResult {
            values: ["42", "420"]
                .into_iter()
                .filter(|value| value.starts_with(&request.argument_value))
                .map(ToOwned::to_owned)
                .collect(),
            total: Some(2),
            has_more: false,
        })
    }

    #[token_validator]
    fn validate_token(
        &self,
        token: McpAccessToken,
        context: McpAuthorizationContext,
    ) -> McpTokenValidation {
        self.validations
            .lock()
            .expect("validations lock")
            .push(format!(
                "{}:{}",
                context.resource,
                context.required_scopes.join(" ")
            ));
        if token.0 == "valid-token" {
            McpTokenValidation::Authorized {
                principal_id: mcp::McpPrincipalId::new("macro-test").expect("valid principal"),
                expires_at: None,
            }
        } else {
            McpTokenValidation::Unauthorized {
                error_description: Some("invalid macro test token".to_owned()),
            }
        }
    }
}

#[tokio::test]
async fn exported_server_macro_dispatches_registered_surface() -> mcp::Result<()> {
    let handler = MacroServer::default();
    let server = RunningServer::start_plain(handler).await?;

    let discover = post_json(&server.endpoint, discover_body("discover-macro")).await?;
    assert_eq!(discover.status, StatusCode::OK);
    assert_eq!(
        discover.body["result"]["_meta"]["io.modelcontextprotocol/serverInfo"]["name"],
        "mcp-macro-test-server"
    );
    assert_eq!(
        discover.body["result"]["_meta"]["io.modelcontextprotocol/serverInfo"]["version"],
        "1.2.3"
    );
    assert_eq!(
        discover.body["result"]["instructions"],
        "Prefer macro-generated handlers."
    );
    assert_eq!(
        discover.body["result"]["capabilities"]["tools"]["listChanged"],
        false
    );
    assert_eq!(
        discover.body["result"]["capabilities"]["prompts"]["listChanged"],
        false
    );
    assert_eq!(
        discover.body["result"]["capabilities"]["resources"]["listChanged"],
        false
    );
    let tools = post_json(
        &server.endpoint,
        json!({ "jsonrpc": "2.0", "id": "tools-list", "method": "tools/list" }),
    )
    .await?;
    assert_eq!(tools.body["result"]["tools"][0]["name"], "echo");
    assert_eq!(tools.body["result"]["nextCursor"], "next-tool-page");

    let tool_call = post_json(
        &server.endpoint,
        json!({
            "jsonrpc": "2.0",
            "id": "tools-call",
            "method": "tools/call",
            "params": { "name": "echo", "arguments": { "value": "marker" } }
        }),
    )
    .await?;
    assert_eq!(
        tool_call.body["result"]["content"][0]["text"],
        "echo:marker"
    );

    let prompts = post_json(
        &server.endpoint,
        json!({ "jsonrpc": "2.0", "id": "prompts-list", "method": "prompts/list" }),
    )
    .await?;
    assert_eq!(prompts.body["result"]["prompts"][0]["name"], "status");
    assert_eq!(prompts.body["result"]["nextCursor"], "next-prompt-page");

    let prompt = post_json(
        &server.endpoint,
        json!({
            "jsonrpc": "2.0",
            "id": "prompts-get",
            "method": "prompts/get",
            "params": { "name": "status" }
        }),
    )
    .await?;
    assert_eq!(
        prompt.body["result"]["messages"][0]["content"]["text"],
        "macro-prompt-status"
    );

    let resources = post_json(
        &server.endpoint,
        json!({ "jsonrpc": "2.0", "id": "resources-list", "method": "resources/list" }),
    )
    .await?;
    assert_eq!(
        resources.body["result"]["resources"][0]["uri"],
        "test://status"
    );
    assert_eq!(resources.body["result"]["nextCursor"], "next-resource-page");

    let templates = post_json(
        &server.endpoint,
        json!({
            "jsonrpc": "2.0",
            "id": "templates-list",
            "method": "resources/templates/list"
        }),
    )
    .await?;
    assert_eq!(
        templates.body["result"]["resourceTemplates"][0]["uriTemplate"],
        "test://items/{id}"
    );
    assert_eq!(templates.body["result"]["nextCursor"], "next-template-page");

    let resource = post_json(
        &server.endpoint,
        json!({
            "jsonrpc": "2.0",
            "id": "resources-read",
            "method": "resources/read",
            "params": { "uri": "test://items/42" }
        }),
    )
    .await?;
    assert_eq!(
        resource.body["result"]["contents"][0]["text"],
        "resource:test://items/42"
    );

    let completion = post_json(
        &server.endpoint,
        json!({
            "jsonrpc": "2.0",
            "id": "completion",
            "method": "completion/complete",
            "params": {
                "ref": { "type": "ref/resource", "uri": "test://items/{id}" },
                "argument": { "name": "id", "value": "42" }
            }
        }),
    )
    .await?;
    assert_eq!(
        completion.body["result"]["completion"]["values"],
        json!(["42", "420"])
    );

    Ok(())
}

#[tokio::test]
async fn exported_server_macro_generates_auth_helpers() -> mcp::Result<()> {
    let handler = MacroServer::default();
    let validations = Arc::clone(&handler.validations);
    let server = RunningServer::start_authorized(handler).await?;

    let metadata = reqwest::Client::new()
        .get(format!(
            "{}/.well-known/oauth-protected-resource/mcp",
            server.origin
        ))
        .send()
        .await?
        .error_for_status()?
        .json::<McpProtectedResourceMetadata>()
        .await?;
    assert_eq!(metadata.resource, server.endpoint);
    assert_eq!(metadata.authorization_servers, ["https://auth.example.com"]);
    assert_eq!(metadata.scopes_supported, ["macro:read"]);
    assert_eq!(
        metadata.resource_name.as_deref(),
        Some("MCP macro test server")
    );

    let unauthorized = reqwest::Client::new()
        .post(&server.endpoint)
        .header("accept", "application/json, text/event-stream")
        .header("content-type", "application/json")
        .header("mcp-protocol-version", MCP_PROTOCOL_VERSION)
        .header("mcp-method", "server/discover")
        .json(&request_body(discover_body("unauthorized")))
        .send()
        .await?;
    assert_eq!(unauthorized.status(), StatusCode::UNAUTHORIZED);
    assert!(
        unauthorized
            .headers()
            .get_all(reqwest::header::WWW_AUTHENTICATE)
            .iter()
            .filter_map(|value| value.to_str().ok())
            .any(|value| value.contains("realm=\"mcp-macro-test\"")
                && value.contains("scope=\"macro:read\""))
    );

    let authorized = reqwest::Client::new()
        .post(&server.endpoint)
        .header("accept", "application/json, text/event-stream")
        .bearer_auth("valid-token")
        .header("content-type", "application/json")
        .header("mcp-protocol-version", MCP_PROTOCOL_VERSION)
        .header("mcp-method", "server/discover")
        .json(&request_body(discover_body("authorized")))
        .send()
        .await?;
    assert_eq!(authorized.status(), StatusCode::OK);
    let body = sse_response(authorized).await?;
    assert_eq!(body["result"]["supportedVersions"][0], MCP_PROTOCOL_VERSION);
    assert_eq!(
        validations.lock().expect("validations lock").as_slice(),
        [format!("{}:macro:read", server.endpoint)]
    );

    Ok(())
}

struct RunningServer {
    endpoint: String,
    origin: String,
    _task: JoinHandle<()>,
}

impl RunningServer {
    async fn start_plain(handler: MacroServer) -> mcp::Result<Self> {
        Self::start_with_router(handler, |handler, _endpoint| {
            Ok(handler.streamable_http_router())
        })
        .await
    }

    async fn start_authorized(handler: MacroServer) -> mcp::Result<Self> {
        Self::start_with_router(handler, |handler, endpoint| {
            let metadata = MacroServer::protected_resource_metadata(
                endpoint.to_owned(),
                ["https://auth.example.com"],
            );
            handler.streamable_http_router_with_auth(metadata)
        })
        .await
    }

    async fn start_with_router(
        handler: MacroServer,
        router: impl FnOnce(MacroServer, &str) -> mcp::Result<mcp::server::StreamableHttpRouter>,
    ) -> mcp::Result<Self> {
        let listener = TcpListener::bind("127.0.0.1:0").await?;
        let address: SocketAddr = listener.local_addr()?;
        let origin = format!("http://{address}");
        let endpoint = format!("{origin}/mcp");
        let router = router(handler, &endpoint)?;
        let task = tokio::spawn(async move {
            if let Err(error) = axum::serve(listener, router).await {
                tracing::debug!(%error, "mcp macro test server stopped");
            }
        });
        Ok(Self {
            endpoint,
            origin,
            _task: task,
        })
    }
}

struct JsonResponse {
    status: StatusCode,
    body: Value,
}

async fn post_json(endpoint: &str, body: Value) -> mcp::Result<JsonResponse> {
    let client = reqwest::Client::new();
    let body = request_body(body);
    let method = body["method"].as_str().unwrap_or_default();
    let mut request = client
        .post(endpoint)
        .header("accept", "application/json, text/event-stream")
        .header("content-type", "application/json")
        .header("mcp-protocol-version", MCP_PROTOCOL_VERSION)
        .header("mcp-method", method)
        .json(&body);
    if let Some(name) = request_name(method, &body) {
        request = request.header("mcp-name", name);
    }
    let response = request.send().await?;
    let status = response.status();
    let body = sse_response(response).await?;
    Ok(JsonResponse { status, body })
}

fn request_body(mut body: Value) -> Value {
    if body.get("params").is_none() {
        body["params"] = json!({});
    }
    body["params"]["_meta"] = json!({
        "io.modelcontextprotocol/protocolVersion": MCP_PROTOCOL_VERSION,
        "io.modelcontextprotocol/clientCapabilities": {},
        "io.modelcontextprotocol/clientInfo": { "name": "macro-tests", "version": "1" }
    });
    body
}

fn request_name<'a>(method: &str, body: &'a Value) -> Option<&'a str> {
    match method {
        "tools/call" | "prompts/get" => body["params"]["name"].as_str(),
        "resources/read" => body["params"]["uri"].as_str(),
        _ => None,
    }
}

async fn sse_response(response: reqwest::Response) -> mcp::Result<Value> {
    let text = response.text().await?;
    let data = text
        .lines()
        .rev()
        .find_map(|line| line.strip_prefix("data: "))
        .ok_or_else(|| mcp::Error::protocol("MCP SSE response omitted data"))?;
    Ok(serde_json::from_str(data)?)
}

fn discover_body(id: &str) -> Value {
    json!({
        "jsonrpc": "2.0",
        "id": id,
        "method": "server/discover"
    })
}

